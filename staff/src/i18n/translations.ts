export const translateStatic = (text: string, language: StaffLanguage) => {
  if (language !== "am") return text;
  if (amharic[text]) return amharic[text];
  const suffixes = [" *", " (Optional)", " (optional)", ":"];
  for (const suffix of suffixes) {
    if (text.endsWith(suffix)) {
      const base = text.slice(0, -suffix.length);
      if (amharic[base]) return `${amharic[base]}${suffix}`;
    }
  }
  return text;
};
